// Writes src/node/countryPlaces.ts: one point per country (ISO 3166 alpha-2), the mean of the places in the time zone
// database's zone.tab for that country (its main cities), so a node with the small country GeoIP database can still
// put members on the globe. Run from app/ on a system with tzdata:
//   node scripts/country-places.mjs [path/to/zone.tab]
import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2] ?? "/usr/share/zoneinfo/zone.tab";
// +DDMM+DDDMM or +DDMMSS+DDDMMSS
const parse = (text, degrees) => {
  const sign = text[0] === "-" ? -1 : 1;
  const d = Number(text.slice(1, 1 + degrees));
  const m = Number(text.slice(1 + degrees, 3 + degrees));
  const s = Number(text.slice(3 + degrees) || 0);
  return sign * (d + m / 60 + s / 3600);
};
const sums = new Map();
for (const line of readFileSync(file, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [code, coordinates] = line.split("\t");
  const [, lat, lon] = /^([+-]\d+)([+-]\d+)$/.exec(coordinates);
  const φ = (parse(lat, 2) * Math.PI) / 180;
  const λ = (parse(lon, 3) * Math.PI) / 180;
  // Averaged as vectors, so countries across the antimeridian don't land on the other side of the world.
  const sum = sums.get(code) ?? [0, 0, 0];
  sums.set(code, [sum[0] + Math.cos(φ) * Math.cos(λ), sum[1] + Math.cos(φ) * Math.sin(λ), sum[2] + Math.sin(φ)]);
}
const round = (n) => Math.round(n * 100) / 100;
const places = Object.fromEntries([...sums].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([code, [x, y, z]]) => [
  code, [round((Math.atan2(z, Math.hypot(x, y)) * 180) / Math.PI), round((Math.atan2(y, x) * 180) / Math.PI)],
]));
writeFileSync(new URL("../src/node/countryPlaces.ts", import.meta.url), `// Generated by scripts/country-places.mjs from the time zone database's zone.tab: [lat, lon] per country.
export const countryPlaces: Record<string, [number, number]> = ${JSON.stringify(places)};
`);
console.log(`${sums.size} countries written`);

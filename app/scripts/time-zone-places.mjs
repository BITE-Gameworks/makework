// Writes src/core/timeZonePlaces.ts: where each time zone is (its main city, [lat, lon]) and its country (ISO 3166
// alpha-2), from the time zone database's zone.tab, plus the old names that link to them (tzdata.zi). A member's
// app places itself from its own time zone for the globe in Server settings > Nodes. Run from app/ with tzdata:
//   node scripts/time-zone-places.mjs [zoneinfo folder]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const parse = (text, degrees) => {
  const sign = text[0] === "-" ? -1 : 1;
  const d = Number(text.slice(1, 1 + degrees));
  const m = Number(text.slice(1 + degrees, 3 + degrees));
  const s = Number(text.slice(3 + degrees) || 0);
  return Math.round(sign * (d + m / 60 + s / 3600) * 100) / 100;
};
const zones = {};
for (const line of readFileSync(join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [code, coordinates, zone] = line.split("\t");
  const [, lat, lon] = /^([+-]\d+)([+-]\d+)$/.exec(coordinates);
  zones[zone] = [parse(lat, 2), parse(lon, 3), code];
}
const links = {};
for (const line of readFileSync(join(dir, "tzdata.zi"), "utf8").split("\n")) {
  const [kind, target, alias] = line.split(" ");
  if (kind === "L" && zones[target] && !zones[alias]) links[alias] = target;
}
writeFileSync(new URL("../src/core/timeZonePlaces.ts", import.meta.url), `// Generated by scripts/time-zone-places.mjs from the time zone database: [lat, lon, country] per zone, and old names.
export const zonePlaces: Record<string, [number, number, string]> = ${JSON.stringify(zones)};
export const zoneLinks: Record<string, string> = ${JSON.stringify(links)};
`);
console.log(`${Object.keys(zones).length} zones, ${Object.keys(links).length} links written`);
